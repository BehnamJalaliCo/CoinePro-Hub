def main() -> None:
    wt = json.load(open(sys.argv[1], encoding="utf-8"))
    lines = {l["n"]: l for l in wt["lines"]}
    voice_end = lines[max(lines)]["end"]

    def t_of(anchor):
        if anchor == 0:
            return 0.0
        if anchor == "voice_end":
            return round(voice_end + 0.25, 2)
        if anchor[0] == "cut":
            n = anchor[1]
            prev_end, start = lines[n - 1]["end"], lines[n]["start"]
            return round(start - min(0.20, max(start - prev_end, 0) / 2), 2)
        n, i = anchor
        return round(max(lines[n]["words"][i]["s"] - LEAD, 0), 2)

    beats = []
    for k, (bid, anchor, title, pic, ons, move, sfx) in enumerate(BEATS):
        beats.append({"id": bid, "shot": int(re.match(r"\d+", bid).group()), "start": t_of(anchor),
                      "title": title, "picture": pic, "on_screen": ons, "motion": move, "sound": sfx})
    for k, b in enumerate(beats):
        b["end"] = beats[k + 1]["start"] if k + 1 < len(beats) else END
        b["dur"] = round(b["end"] - b["start"], 2)
        b["voice"] = " ".join(w["w"] for l in wt["lines"] for w in l["words"]
                              if b["start"] - 0.05 <= w["s"] < b["end"] - 0.05)
    # subtitles: chunks of at most 5 words, broken after punctuation, shown until the next chunk (or a pause)
    subs = []
    for l in wt["lines"]:
        cur = []
        for i, w in enumerate(l["words"]):
            cur.append(w)
            brk = re.search(r"[،.:؟…»]$", w["w"]) and len(cur) >= 2
            if len(cur) >= 5 or brk or i == len(l["words"]) - 1:
                subs.append({"line": l["n"], "words": cur})
                cur = []
    for c in subs:
        c["start"] = round(c["words"][0]["s"] - 0.05, 2)
    for k, c in enumerate(subs):
        nxt = subs[k + 1]["start"] if k + 1 < len(subs) else None
        c["end"] = round(min(nxt, c["words"][-1]["e"] + 0.35) if nxt else c["words"][-1]["e"] + 0.4, 2)
        c["text"] = " ".join(w["w"] for w in c["words"])
    long_beats = [(b["id"], b["dur"]) for b in beats if b["dur"] > MAX_STILL]
    out = {"voice": "qc/voice_final.wav", "video_end": END, "voice_end": voice_end, "fps": 60,
           "size": [1080, 1920], "beats": beats, "subtitles": subs, "long_beats": long_beats,
           "music": "موسیقی ساخته‌ی خودمان، آرام و ضرب‌دار (حدود ۹۵ ضرب در دقیقه)، ۲۲ دسی‌بل زیر صدای گوینده؛ در شات ۱۰ پایین‌تر، در شعار دو ضرب پررنگ."}
    json.dump(out, open(sys.argv[2], "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    for b in beats:
        print(b["id"], b["start"], b["end"], b["dur"], b["title"])
    print("subtitle chunks", len(subs), "long beats", long_beats)


if __name__ == "__main__":
    main()
