#!/usr/bin/env python3
"""Generate the Android design-system sources from design/ (the single source of truth).

    design/tokens/divan.tokens.json  -> designsystem/generated/DivanTokens.kt
    design/icons/icons.json          -> designsystem/generated/DivanIconData.kt
    design/brand/**/*-flat.svg       -> designsystem/generated/BrandData.kt, launcher foreground
    design/fonts/variable/*.ttf      -> res/font/

Usage: python3 scripts/gen_assets.py [--check]
--check regenerates in memory and exits 1 if any committed output differs (for CI).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ANDROID = Path(__file__).resolve().parent.parent
ROOT = ANDROID.parent.parent
DESIGN = ROOT / "design"
APP = ANDROID / "app" / "src" / "main"
GEN = APP / "java" / "com" / "coinepro" / "hq" / "designsystem" / "generated"
HEADER = "// Generated by apps/android/scripts/gen_assets.py from design/. Do not edit.\n"

outputs: dict[Path, bytes] = {}


def out(path: Path, content: str | bytes) -> None:
    outputs[path] = content.encode() if isinstance(content, str) else content


# ---------------------------------------------------------------- tokens --
tokens = json.loads((DESIGN / "tokens" / "divan.tokens.json").read_text())["divan"]


def node(path: str):
    cur = {"divan": tokens}
    for part in path.split("."):
        cur = cur[part]
    return cur


def value(v):
    if isinstance(v, dict):
        v = v.get("$value", v.get("value"))
    while isinstance(v, str) and v.startswith("{"):
        v = node(v.strip("{}"))
        if isinstance(v, dict):
            v = v.get("$value", v.get("value"))
    return v


def argb(v) -> str:
    v = value(v)
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})", v)
    if m:
        return f"0xFF{m.group(1).upper()}"
    m = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", v)
    if m:
        r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
        return f"0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X}"
    raise ValueError(f"unsupported colour {v!r}")


def palette(theme: str) -> str:
    c = tokens["color"][theme]
    chart = tokens["color"]["chart"]
    f = {
        "page": c["surface"]["page"], "card": c["surface"]["card"], "tile": c["surface"]["tile"],
        "raised": c["surface"]["raised"], "overlay": c["surface"]["overlay"], "hover": c["surface"]["hover"],
        "pressed": c["surface"]["pressed"],
        "textPrimary": c["text"]["primary"], "textSecondary": c["text"]["secondary"], "textMuted": c["text"]["muted"],
        "onGold": c["text"]["onGold"], "onSilver": c["text"]["onSilver"],
        "lineHairline": c["line"]["hairline"], "lineDivider": c["line"]["divider"], "lineStrong": c["line"]["strong"],
        "lineTahrir": c["line"]["tahrir"],
        "goldFill": c["gold"]["fill"], "goldInk": c["gold"]["ink"], "goldBright": c["gold"]["bright"], "goldDeep": c["gold"]["deep"],
        "silverFill": c["silver"]["fill"], "silverInk": c["silver"]["ink"],
        "lapis": c["lapis"], "positive": c["positive"], "negative": c["negative"], "warning": c["warning"], "learning": c["learning"],
        "softGold": c["soft"]["gold"], "softPositive": c["soft"]["positive"], "softNegative": c["soft"]["negative"],
        "softWarning": c["soft"]["warning"], "softLapis": c["soft"]["lapis"], "softLearning": c["soft"]["learning"],
        "scrim": c["state"]["scrim"], "disabledText": c["state"]["disabledText"], "disabledFill": c["state"]["disabledFill"],
        "focus": c["state"]["focus"], "skeleton": c["state"]["skeleton"], "skeletonHi": c["state"]["skeletonHi"],
        # The two metals of the marks: silver + gold by night, graphite + ink gold by day.
        "markSilver": c["silver"]["fill"] if theme == "night" else c["silver"]["ink"],
        "markGold": c["gold"]["ink"],
    }
    lines = [f"    {k} = Color({argb(v)})," for k, v in f.items()]
    cat = chart["categorical"][theme]
    seq = chart["sequentialGold"][theme]
    lines.append("    chart = listOf(" + ", ".join(f"Color({argb(cat[str(i)])})" for i in range(1, 9)) + "),")
    lines.append("    sequentialGold = listOf(" + ", ".join(f"Color({argb(seq[str(i)])})" for i in range(1, 7)) + "),")
    return "\n".join(lines)


fields = [
    "page", "card", "tile", "raised", "overlay", "hover", "pressed", "textPrimary", "textSecondary", "textMuted",
    "onGold", "onSilver", "lineHairline", "lineDivider", "lineStrong", "lineTahrir", "goldFill", "goldInk",
    "goldBright", "goldDeep", "silverFill", "silverInk", "lapis", "positive", "negative", "warning", "learning",
    "softGold", "softPositive", "softNegative", "softWarning", "softLapis", "softLearning", "scrim", "disabledText",
    "disabledFill", "focus", "skeleton", "skeletonHi", "markSilver", "markGold",
]
motion = tokens["motion"]
font = tokens["font"]
slots = tokens["color"]["chart"]["slots"]["tokenType"]
ms = lambda k: int(str(value(motion["duration"][k])).removesuffix("ms"))  # noqa: E731
px = lambda v: int(str(value(v)).removesuffix("px"))  # noqa: E731
ease = lambda k: ", ".join(f"{x}f" for x in value(motion["easing"][k]))  # noqa: E731

out(GEN / "DivanTokens.kt", f"""{HEADER}package com.coinepro.hq.designsystem.generated

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/** Divan {value(tokens["meta"]["version"])} colours for one theme (night or day). */
@Immutable
data class DivanPalette(
{chr(10).join(f"    val {f}: Color," for f in fields)}
    /** Categorical chart palette v2, slots 1..8 (index 0 = slot 1). Fixed order, never cycled. */
    val chart: List<Color>,
    /** Sequential gold ramp, light to dark by magnitude. */
    val sequentialGold: List<Color>,
)

val NightPalette = DivanPalette(
{palette("night")}
)

val DayPalette = DivanPalette(
{palette("day")}
)

/** Fixed colours outside the theme ladder. */
object DivanFixed {{
    val lapisDisc = Color(0xFF121A33)
    val orbLight = Color({argb(tokens["color"]["primitive"]["gold"]["300"])})
    val orbMid = Color({argb(tokens["color"]["primitive"]["gold"]["500"])})
    val orbDeep = Color({argb(tokens["color"]["primitive"]["gold"]["700"])})
    val levelUrgent = Color({argb(tokens["color"]["level"]["urgent"])})
    val levelDecision = Color({argb(tokens["color"]["level"]["decision"])})
    val levelReport = Color({argb(tokens["color"]["level"]["report"])})
    val levelInfo = Color({argb(tokens["color"]["level"]["info"])})
    val levelLearning = Color({argb(tokens["color"]["level"]["learning"])})
}}

/** Chart slot of each token type (palette v2). */
object TokenTypeSlot {{
    const val INPUT = {value(slots["input"])}
    const val OUTPUT = {value(slots["output"])}
    const val CACHE = {value(slots["cache"])}
    const val THINKING = {value(slots["thinking"])}
}}

object DivanMotion {{
    const val MICRO_MS = {ms("micro")}
    const val STATE_MS = {ms("state")}
    const val TRANSITION_MS = {ms("transition")}
    const val CEREMONY_MS = {ms("ceremony")}
    const val SEAL_HOLD_MS = {ms("sealHold")}
    val STANDARD = floatArrayOf({ease("standard")})
    val CEREMONY = floatArrayOf({ease("ceremony")})
}}

/** Type scale in sp: size to line height. */
object DivanType {{
{chr(10).join(f"    const val {k.upper()}_SIZE = {px(v)}" for k, v in font["size"].items())}
{chr(10).join(f"    const val {k.upper()}_LINE = {px(v)}" for k, v in font["lineHeight"].items())}
}}
""")

# ----------------------------------------------------------------- icons --
icons = json.loads((DESIGN / "icons" / "icons.json").read_text())


def const(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


rows = []
for ic in icons["icons"]:
    h = ic.get("h")
    rows.append(f'    {const(ic["id"])}("{ic["id"]}", "{ic["s"]}", {json.dumps(h) if h else "null"}, {str(bool(ic.get("mirror"))).lower()}),')
out(GEN / "DivanIconData.kt", f"""{HEADER}package com.coinepro.hq.designsystem.generated

/** Divan icon set ({len(rows)} glyphs): {icons["grid"]}-grid, {icons["stroke"]} stroke, round caps and joins.
 *  [stroke] is drawn as an outline; [heart] is the filled part shown in the active state;
 *  [mirror] glyphs have a direction and flip in RTL. */
enum class DivanIcon(val id: String, val stroke: String, val heart: String?, val mirror: Boolean) {{
{chr(10).join(rows)}
}}
""")

# ----------------------------------------------------------------- brand --
ATTR = re.compile(r'([a-zA-Z:-]+)="([^"]*)"')


def attrs(s: str) -> dict[str, str]:
    return dict(ATTR.findall(s))


def svg_of(path: Path):
    src = path.read_text()
    vb = attrs(re.search(r"<svg\s([^>]*)>", src).group(1))["viewBox"]
    paths = [attrs(m) for m in re.findall(r"<path\s([^>]*?)/?>", src)]
    return [float(x) for x in vb.split()], paths


def two(path: Path):
    vb, paths = svg_of(path)

    def pick(i: str, fill: str) -> str:
        p = next((p for p in paths if p.get("id") == i), None) or next(p for p in paths if p.get("fill", "").upper() == fill)
        return p["d"]

    return vb, pick("silver", "#DBDBDB"), pick("gold", "#D8A848")


def layers(path: Path):
    vb, paths = svg_of(path)
    res = []
    for p in paths:
        m = re.search(r"var\(--logo-(ink|accent),\s*(#[0-9A-Fa-f]{3,8})\)", p.get("fill", ""))
        res.append((m.group(1) if m else "ink", (m.group(2) if m else "#000000").upper(), p["d"]))
    return vb, res


def kvb(vb) -> str:
    return f"floatArrayOf({', '.join(f'{x:g}f' for x in vb)})"


def kcolor(hexstr: str) -> str:
    h = hexstr.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return f"0xFF{h.upper()}"


mvb, msil, mgold = two(DESIGN / "brand" / "coinepro-monogram-flat.svg")
wvb, wsil, wgold = two(DESIGN / "brand" / "coinepro-wordmark-flat.svg")
companies = []
co_dir = DESIGN / "brand" / "companies"
for d in sorted(p for p in co_dir.iterdir() if p.is_dir()):
    mark = next((f for f in sorted(d.iterdir()) if re.search(r"-mark-flat\.svg$", f.name)), None)
    word = next((f for f in sorted(d.iterdir()) if re.search(r"-wordmark(-fa)?-flat\.svg$", f.name)), None)
    if not mark:
        continue

    def mk(f: Path) -> str:
        vb, ls = layers(f)
        body = ", ".join(f'MarkLayer(MarkRole.{r.upper()}, {kcolor(c)}, "{dd}")' for r, c, dd in ls)
        return f"BrandMark({kvb(vb)}, listOf({body}))"

    companies.append(f'        "{d.name.upper()}" to CompanyBrand({mk(mark)}, {mk(word) if word else "null"}),')

out(GEN / "BrandData.kt", f"""{HEADER}package com.coinepro.hq.designsystem.generated

enum class MarkRole {{ INK, ACCENT }}

/** One filled layer of a mark; [color] is the brand colour (ARGB) used when the mark is not drawn in one ink. */
class MarkLayer(val role: MarkRole, val color: Long, val path: String)

/** A vector mark: viewBox (minX, minY, width, height) and its layers. */
class BrandMark(val viewBox: FloatArray, val layers: List<MarkLayer>)

class CompanyBrand(val mark: BrandMark, val wordmark: BrandMark?)

/** The owner's marks (two metals) and every company's own mark, keyed by company code
 *  (design/brand/companies/<code>/). A company without a mark falls back to its code. */
object BrandData {{
    val monogramViewBox = {kvb(mvb)}
    const val MONOGRAM_SILVER = "{msil}"
    const val MONOGRAM_GOLD = "{mgold}"
    val wordmarkViewBox = {kvb(wvb)}
    const val WORDMARK_SILVER = "{wsil}"
    const val WORDMARK_GOLD = "{wgold}"
    val companies: Map<String, CompanyBrand> = mapOf(
{chr(10).join(companies)}
    )
}}
""")

# Launcher foreground: the monogram centred in the 108dp adaptive-icon canvas (72dp safe zone).
def launcher(mono: bool) -> str:
    x, y, w, h = mvb
    scale = 58.0 / max(w, h)
    tx = 54 - (x + w / 2) * scale
    ty = 54 - (y + h / 2) * scale
    sil = "#FFFFFFFF" if mono else "#FFDBDBDB"
    gold = "#FFFFFFFF" if mono else "#FFD8A848"
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/android/scripts/gen_assets.py from design/brand. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{tx:.3f}" android:translateY="{ty:.3f}" android:scaleX="{scale:.5f}" android:scaleY="{scale:.5f}">
        <path android:fillColor="{sil}" android:fillType="evenOdd" android:pathData="{msil}"/>
        <path android:fillColor="{gold}" android:fillType="evenOdd" android:pathData="{mgold}"/>
    </group>
</vector>
"""


out(APP / "res" / "drawable" / "ic_launcher_foreground.xml", launcher(False))
out(APP / "res" / "drawable" / "ic_launcher_monochrome.xml", launcher(True))

# ----------------------------------------------------------------- fonts --
# One typeface, IRANYekanX: the FaNum cut draws ASCII digits as Persian (prose), the Latin cut keeps
# figures Latin (money, tokens, codes). Both are variable fonts (weight axis).
for src, dst in (("IRANYekanXVF.ttf", "iranyekanx_latin.ttf"), ("IRANYekanXVFaNumVF.ttf", "iranyekanx_fanum.ttf")):
    out(APP / "res" / "font" / dst, (DESIGN / "fonts" / "variable" / src).read_bytes())

# ------------------------------------------------------------------ write --
check = "--check" in sys.argv[1:]
stale = []
for path, data in outputs.items():
    if check:
        if not path.exists() or path.read_bytes() != data:
            stale.append(path.relative_to(ROOT))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
if check:
    if stale:
        print("stale generated files:", *map(str, stale), sep="\n  ")
        sys.exit(1)
    print(f"generated files up to date ({len(outputs)})")
else:
    print(f"tokens: ok · icons: {len(rows)} · companies: {len(companies)} · fonts: 2 · files: {len(outputs)}")
