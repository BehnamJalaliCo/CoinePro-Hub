// Generates the web's design assets from the single sources in design/:
//   design/tokens/divan.tokens.json  -> src/styles/tokens.css
//   design/icons/svg/*.svg           -> src/generated/icons.ts
//   design/brand/**/*-flat.svg       -> src/generated/brand.ts
//   design/fonts/variable/*.woff2    -> public/fonts/
// The outputs are committed so the Docker build needs only apps/web; CI runs
// `npm run gen:check` to prove they match their sources.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..');
const design = join(web, '..', '..', 'design');
const out = (p, s) => { mkdirSync(dirname(join(web, p)), { recursive: true }); writeFileSync(join(web, p), s); };
const HEADER = '/* Generated by apps/web/scripts/gen-assets.mjs from design/. Do not edit. */\n';

// ---------------------------------------------------------------- tokens --
const T = JSON.parse(readFileSync(join(design, 'tokens', 'divan.tokens.json'), 'utf8'));
const get = (path) => path.split('.').reduce((o, k) => o?.[k], T);
const resolve = (v) => {
  let x = v;
  for (let i = 0; i < 8 && typeof x === 'string' && x.startsWith('{'); i++) x = get(x.slice(1, -1)).$value;
  return x;
};
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const flat = (node, prefix, acc) => {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) acc.push([`${prefix}-${kebab(k)}`, resolve(v.$value)]);
    else if (v && typeof v === 'object') flat(v, `${prefix}-${kebab(k)}`, acc);
  }
  return acc;
};
const D = T.divan;
const themeVars = (name) => flat(D.color[name], '--hq', []).map(([k, v]) => `  ${k}: ${v};`).join('\n');
const scalar = [
  ...flat(D.space, '--hq-space', []),
  ...flat(D.radius, '--hq-radius', []),
  ...flat(D.size, '--hq-size', []),
  ...flat(D.font.size, '--hq-text', []),
  ...flat(D.font.lineHeight, '--hq-leading', []),
  ...flat(D.motion.duration, '--hq-dur', []),
].map(([k, v]) => `  ${k}: ${v};`);
const ease = (a) => `cubic-bezier(${resolve(a).join(', ')})`;
scalar.push(`  --hq-ease-standard: ${ease(D.motion.easing.standard.$value)};`);
scalar.push(`  --hq-ease-ceremony: ${ease(D.motion.easing.ceremony.$value)};`);
const chart = (mode) => Object.entries(D.color.chart.categorical[mode]).map(([k, v]) => `  --hq-chart-${k}: ${v.$value};`).join('\n');
const seq = (mode) => Object.entries(D.color.chart.sequentialGold[mode]).map(([k, v]) => `  --hq-seq-${k}: ${v.$value};`).join('\n');
const css = `${HEADER}/* Divan ${D.meta.version.$value}. Night is the default; day via [data-theme="day"] or the system setting. */
:root {
${scalar.join('\n')}
}
:root, [data-theme="night"] {
  color-scheme: dark;
${themeVars('night')}
${chart('night')}
${seq('night')}
  --hq-lapis-disc: #121A33;
}
[data-theme="day"] {
  color-scheme: light;
${themeVars('day')}
${chart('day')}
${seq('day')}
  --hq-lapis-disc: #121A33;
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
    color-scheme: light;
${themeVars('day').replace(/^ {2}/gm, '    ')}
${chart('day').replace(/^ {2}/gm, '    ')}
${seq('day').replace(/^ {2}/gm, '    ')}
  }
}
`;
out('src/styles/tokens.css', css);

// ----------------------------------------------------------------- icons --
const attrs = (s) => Object.fromEntries([...s.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const iconDir = join(design, 'icons', 'svg');
const icons = {};
for (const f of readdirSync(iconDir).filter((f) => f.endsWith('.svg')).sort()) {
  const src = readFileSync(join(iconDir, f), 'utf8');
  const body = src.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  const els = [...body.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s([^>]*?)\/?>/g)].map((m) => {
    const a = attrs(m[2]);
    const role = a.class === 'heart' ? 'heart' : 'stroke';
    delete a.class;
    if (role === 'heart') { delete a.fill; delete a.stroke; }
    return { tag: m[1], role, a };
  });
  icons[basename(f, '.svg')] = els;
}
out('src/generated/icons.ts', `${HEADER}export type IconElement = { tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse'; role: 'stroke' | 'heart'; a: Record<string, string> };
export const ICONS = ${JSON.stringify(icons, null, 1)} as const satisfies Record<string, readonly IconElement[]>;
export type IconName = keyof typeof ICONS;
`);

// ----------------------------------------------------------------- brand --
const svgOf = (file) => {
  const src = readFileSync(file, 'utf8');
  const vb = attrs(src.match(/<svg\s([^>]*)>/)[1]).viewBox;
  const paths = [...src.matchAll(/<path\s([^>]*?)\/?>/g)].map((m) => attrs(m[1]));
  return { vb, paths };
};
const two = (file) => {
  const { vb, paths } = svgOf(file);
  // Layers are identified by id (silver/gold) or, failing that, by their brand fill.
  const pick = (id, fill) => (paths.find((p) => p.id === id) ?? paths.find((p) => (p.fill || '').toUpperCase() === fill))?.d;
  return { vb, silver: pick('silver', '#DBDBDB'), gold: pick('gold', '#D8A848') };
};
const layers = (file) => {
  const { vb, paths } = svgOf(file);
  return {
    vb,
    layers: paths.map((p) => {
      const m = /var\(--logo-(ink|accent),\s*(#[0-9A-Fa-f]{3,8})\)/.exec(p.fill || '');
      return { role: m ? m[1] : 'ink', color: m ? m[2] : '#000000', d: p.d };
    }),
  };
};
const brand = {
  monogram: two(join(design, 'brand', 'coinepro-monogram-flat.svg')),
  wordmark: two(join(design, 'brand', 'coinepro-wordmark-flat.svg')),
  companies: {},
};
const coDir = join(design, 'brand', 'companies');
for (const code of readdirSync(coDir).filter((d) => !d.includes('.')).sort()) {
  const files = readdirSync(join(coDir, code));
  const mark = files.find((f) => /-mark-flat\.svg$/.test(f));
  const word = files.find((f) => /-wordmark(-fa)?-flat\.svg$/.test(f));
  if (!mark) continue;
  brand.companies[code.toUpperCase()] = { mark: layers(join(coDir, code, mark)), ...(word ? { wordmark: layers(join(coDir, code, word)) } : {}) };
}
out('src/generated/brand.ts', `${HEADER}// Company marks are data keyed by company code (design/brand/companies/<code>/). A company without a mark falls back to its code.
export type Layer = { role: 'ink' | 'accent'; color: string; d: string };
export type Mark = { vb: string; layers: Layer[] };
export const BRAND = ${JSON.stringify(brand)} as {
  monogram: { vb: string; silver: string; gold: string };
  wordmark: { vb: string; silver: string; gold: string };
  companies: Record<string, { mark: Mark; wordmark?: Mark }>;
};
`);

// ----------------------------------------------------------------- fonts --
mkdirSync(join(web, 'public', 'fonts'), { recursive: true });
for (const [src, dst] of [['IRANYekanXVF.woff2', 'iranyekanx-latin.woff2'], ['IRANYekanXVFaNumVF.woff2', 'iranyekanx-fanum.woff2']]) {
  const from = join(design, 'fonts', 'variable', src);
  if (existsSync(from)) copyFileSync(from, join(web, 'public', 'fonts', dst));
}
console.log(`tokens: ok · icons: ${Object.keys(icons).length} · companies: ${Object.keys(brand.companies).join(', ')} · fonts: 2`);
