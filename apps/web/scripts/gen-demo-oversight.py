#!/usr/bin/env python3
"""Demo protocols for mock mode (src/lib/api/mock-protocols.ts) from the real register, agents/protocols/oversight.yaml.

Development only: the fixtures never reach a production build. Run after the register changes. Deterministic.
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / 'agents/protocols/oversight.yaml'
OUT = ROOT / 'apps/web/src/lib/api/mock-protocols.ts'

# A plausible last run for the demo: most pass, a few fail or are partial (the same ones every time).
FAILED = {'PR-001': ('fail', 2), 'PR-010': ('fail', 1), 'PR-021': ('fail', 1), 'PR-070': ('fail', 1), 'PR-080': ('partial', 1), 'PR-091': ('partial', 1)}


def main() -> None:
    reg = yaml.safe_load(SRC.read_text(encoding='utf-8'))
    out = []
    for i, p in enumerate(reg['protocols']):
        result, findings = FAILED.get(p['ref'], ('pass', 0))
        paused = p.get('status') == 'paused'  # its feature is not built yet: never run
        out.append({
            'id': f"p{i}", 'ref': p['ref'], 'title_fa': p['title_fa'], 'area': p['area'], 'check_md': p['check'], 'method': p['method'],
            'schedule': p['schedule'], 'scope': p['scope'], 'evidence_md': p['evidence'], 'severity': p['severity'], 'answerable': p['answerable'],
            'status': p.get('status', 'active'), 'version': reg['version'], 'sealed_at': '@-4320m',
            'last_run': None if paused else {'at': f"@-{(i * 37) % 600 + 5}m", 'result': result, 'findings': findings},
        })
    OUT.write_text(
        '// Generated by scripts/gen-demo-oversight.py from agents/protocols/oversight.yaml — demo only. Do not edit.\n'
        '// "@-Nm" instants are resolved by the mock to now minus N minutes.\n'
        f'export const DEMO_PROTOCOLS = {json.dumps(out, ensure_ascii=False, indent=1)};\n',
        encoding='utf-8',
    )
    print(f'{len(out)} protocols -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
