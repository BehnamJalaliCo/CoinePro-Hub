@pytest.mark.parametrize(("raw", "want"), CASES)
def test_normalise(raw: str, want: str) -> None:
    assert F.normalise(raw) == want


def test_there_are_at_least_fifty_sentences() -> None:
    assert len(CASES) >= 50


def test_normalise_is_idempotent() -> None:
    for raw, _ in CASES:
        once = F.normalise(raw)
        assert F.normalise(once) == once, raw


def test_words_ignore_zwnj_and_punctuation() -> None:
    assert F.words(f"می{Z}خواهم، بروم؟") == F.words("می خواهم بروم")
    assert F.words("Hello, دنیا!") == ["hello", "دنیا"]


def test_word_error_rate() -> None:
    assert F.wer("من به خانه رفتم", "من به خانه رفتم") == 0.0
    assert F.wer("من به خانه رفتم", "من خانه رفتم") == 0.25  # one deletion
    assert F.wer("من به خانه رفتم", "من به مدرسه رفتم") == 0.25  # one substitution
    assert F.wer("من رفتم", "من دیروز رفتم") == 0.5  # one insertion
    assert F.wer("", "") == 0.0
    assert F.wer("", "یک کلمه") == 2.0
    assert F.wer("می خواهم", f"می{Z}خواهم") == 0.0
    assert F.word_edit_distance("الف ب ج", "الف ج د") == 2
